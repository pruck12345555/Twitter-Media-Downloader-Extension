import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');

const FILENAME_FILE = path.join(ROOT, 'src/utils/filename.js');
const FILE_SAVER_FILE = path.join(ROOT, 'src/utils/file-saver.js');
const EXTRACTOR_FILE = path.join(ROOT, 'src/content/extractor.js');
const VIDEO_FILE = path.join(ROOT, 'src/utils/video.js');
const INTERCEPTOR_FILE = path.join(ROOT, 'src/content/interceptor.js');
const MAIN_FILE = path.join(ROOT, 'src/content/main.js');
const OUTPUT_FILE = path.join(ROOT, 'src/content/content.js');

function cleanModuleCode(code) {
  return code
    .replace(/^import\s+[^;]+;?\r?\n/gm, '') // Strip import lines
    .replace(/^export\s+(const|let|var|function|class|async function)\s+/gm, '$1 ') // Convert export to local
    .replace(/^export\s+default\s+[^;]+;?\r?\n/gm, '') // Strip export default
    .replace(/^export\s*\{[^}]*\};?\r?\n/gm, ''); // Strip export { ... }
}

const filenameCode = cleanModuleCode(fs.readFileSync(FILENAME_FILE, 'utf8'));
const fileSaverCode = cleanModuleCode(fs.readFileSync(FILE_SAVER_FILE, 'utf8'));
const extractorCode = cleanModuleCode(fs.readFileSync(EXTRACTOR_FILE, 'utf8'));
const videoCode = cleanModuleCode(fs.readFileSync(VIDEO_FILE, 'utf8'));
const interceptorCode = cleanModuleCode(fs.readFileSync(INTERCEPTOR_FILE, 'utf8'));
const mainCode = cleanModuleCode(fs.readFileSync(MAIN_FILE, 'utf8'));

const bundled = `/**
 * Twitter Media Downloader - Content Script Bundle
 * Auto-generated by scripts/build.mjs - DO NOT EDIT DIRECTLY
 */
(() => {
  'use strict';

  // --- Utility: Filename & Sanitizer ---
  ${filenameCode.split('\n').join('\n  ')}

  // --- Utility: DOM & Media Extractor ---
  ${extractorCode.split('\n').join('\n  ')}

  // --- Utility: Video Variant Selector ---
  ${videoCode.split('\n').join('\n  ')}

  // --- Utility: System Path File Saver ---
  ${fileSaverCode.split('\n').join('\n  ')}

  // --- Utility: In-Page Twitter Network & React Interceptor ---
  ${interceptorCode.split('\n').join('\n  ')}

  // --- Content Script Main Logic ---
  ${mainCode.split('\n').join('\n  ')}
})();
`;

fs.writeFileSync(OUTPUT_FILE, bundled, 'utf8');
console.log(`Successfully bundled content script -> ${OUTPUT_FILE} (${bundled.length} bytes)`);
